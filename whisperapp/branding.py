def trouble_text(hotkey, has_access, mic_ok, model_ok, log_path, log_button=True,
                 stale_access=False, can_listen=True):
    def mark(ok):
        return "работает" if ok else "не работает"

    access_note = "работает"
    if not has_access:
        access_note = "не работает"
    elif stale_access:
        access_note = "числится, но система его глушит"

    lines = [
        f"Горячая клавиша: {hotkey}",
        f"Разрешение слышать нажатия: {mark(can_listen)}",
        f"Разрешение печатать за вас: {access_note}",
        f"Микрофон: {mark(mic_ok)}",
        f"Распознавание: {mark(model_ok)}",
        "",
    ]
    if not can_listen:
        lines += [
            "Главное, что мешает — программа не видит нажатий.",
            "Системные настройки → Конфиденциальность и безопасность → "
            f"Мониторинг ввода → включите «{APP_NAME}».",
            "",
        ]
    elif stale_access and has_access:
        lines += [stale_access_text().split("\n\n", 1)[1], ""]
    elif not has_access:
        lines += [
            "Главное, что мешает — нет разрешения на нажатие клавиш.",
            "Нажмите «Открыть настройки» ниже и включите там "
            f"«{APP_NAME}».",
            "",
        ]
    elif not mic_ok:
        lines += [
            "Нет доступа к микрофону. Системные настройки → "
            "Конфиденциальность и безопасность → Микрофон.",
            "",
        ]
    elif not model_ok:
        lines += [
            "Распознавание не включилось. Чаще всего помогает перезапуск: "
            "выйдите через меню и откройте программу заново.",
            "",
        ]
    else:
        lines += [
            "Все проверки прошли. Если горячая клавиша всё равно молчит, "
            "её мог занять кто-то другой — попробуйте выбрать другую "
            "в пункте «Горячая клавиша».",
            "",
        ]
    if log_button:
        lines.append(
            "Нужны подробности — кнопка «Показать журнал» ниже откроет "
            f"{pretty_path(log_path)}"
        )
    else:
        lines.append(f"Подробности пишутся в {pretty_path(log_path)}")
    return "\n".join(lines)
